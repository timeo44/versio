// Bundles the API into a single file for Supabase Edge Functions (Deno).
import { build } from "esbuild";
import { mkdirSync } from "node:fs";

mkdirSync("supabase/functions/versio-api", { recursive: true });
await build({
  entryPoints: ["supabase/functions-src/versio-api.ts"],
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  outfile: "supabase/functions/versio-api/index.ts",
  banner: { js: "// @ts-nocheck\n// GENERATED by scripts/build-function.mjs — do not edit. Source: lib/server/*" },
  logLevel: "info",
});
